CREATE TABLE CLIENTE (
    CODIGO   INTEGER      NOT NULL,
    NOME     VARCHAR(100) NOT NULL,
    CIDADE   VARCHAR(60)  NOT NULL,
    UF       CHAR(2)      NOT NULL, 
    CONSTRAINT PK_CLIENTE PRIMARY KEY (CODIGO)
);
 
CREATE TABLE PRODUTO (
    CODIGO       INTEGER        NOT NULL,
    DESCRICAO    VARCHAR(100)   NOT NULL,
    PRECO_VENDA  NUMERIC(15, 2) DEFAULT 0 NOT NULL, 
    CONSTRAINT PK_PRODUTO PRIMARY KEY (CODIGO)
);
 
CREATE TABLE PEDIDO (
    NUMERO_PEDIDO   INTEGER        NOT NULL,
    DATA_EMISSAO    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CODIGO_CLIENTE  INTEGER        NOT NULL,
    VALOR_TOTAL     NUMERIC(15, 2) DEFAULT 0 NOT NULL,    
    CONSTRAINT PK_PEDIDO PRIMARY KEY (NUMERO_PEDIDO)
);
 
CREATE TABLE PEDIDO_ITEM (
    ID              INTEGER        NOT NULL,
    NUMERO_PEDIDO   INTEGER        NOT NULL,
    CODIGO_PRODUTO  INTEGER        NOT NULL,
    QUANTIDADE      NUMERIC(15, 2) NOT NULL,
    VLR_UNITARIO    NUMERIC(15, 2) NOT NULL,
    VLR_TOTAL       NUMERIC(15, 2) NOT NULL, 
    CONSTRAINT PK_PEDIDO_ITEM PRIMARY KEY (ID)
);


ALTER TABLE PEDIDO ADD CONSTRAINT FK_PEDIDO_CLIENTE
  FOREIGN KEY (CODIGO_CLIENTE) REFERENCES CLIENTE (CODIGO) USING INDEX IX_PEDIDO_CODIGO_CLIENTE;
 
ALTER TABLE PEDIDO_ITEM ADD CONSTRAINT FK_PEDIDO_ITEM_PEDIDO
  FOREIGN KEY (NUMERO_PEDIDO) REFERENCES PEDIDO (NUMERO_PEDIDO) USING INDEX IX_PEDIDO_ITEM_NUMERO_PEDIDO;
 
ALTER TABLE PEDIDO_ITEM ADD CONSTRAINT FK_PEDIDO_ITEM_PRODUTO
  FOREIGN KEY (CODIGO_PRODUTO) REFERENCES PRODUTO (CODIGO) USING INDEX IX_PEDIDO_ITEM_CODIGO_PRODUTO;
  

CREATE SEQUENCE GEN_PEDIDO;
 
CREATE SEQUENCE GEN_PEDIDO_ITEM_ID;  
 

CREATE TRIGGER TRG_PEDIDO_BI FOR PEDIDO
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.NUMERO_PEDIDO IS NULL) THEN
    NEW.NUMERO_PEDIDO = NEXT VALUE FOR GEN_PEDIDO;
END;
 
CREATE TRIGGER TRG_PEDIDO_ITEM_BI FOR PEDIDO_ITEM
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.ID IS NULL) THEN
    NEW.ID = NEXT VALUE FOR GEN_PEDIDO_ITEM_ID;
END;

